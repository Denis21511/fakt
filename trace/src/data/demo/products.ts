export const demoProductId = (n: number) => `demo-p${String(n).padStart(2, '0')}`;

export function buildDemoProducts(): Product[] {
  return INPUTS.map((p) => ({
    id: demoProductId(p.n),
    token: p.token,
    name: p.name,
    category: p.category,
    sku: p.sku,
    serial: p.serial,
    description: p.description,
    photo: p.drawing ? { kind: 'drawing', variant: p.drawing } : null,
    manufacturer: 'ФОРМАТ МЕТАЛЛ',
    model: p.model,
    material: p.material,
    dimensions: { width: p.dims[0], height: p.dims[1], depth: p.dims[2] },
    color: p.color,
    manufacturedAt: p.manufacturedAt,
    equipment: [...p.equipment],
    specs: p.specs.map(([label, value]): SpecRow => ({ label, value })),
    warranty: p.warranty
      ? { months: p.warranty.months, startDate: p.warranty.start, terms: p.warranty.terms }
      : { months: null, startDate: null, terms: '' },
    passport: { status: p.status, publishedAt: p.publishedAt ?? null },
    createdAt: p.createdAt,
    updatedAt: p.updatedAt,
    demo: true,
  }));
}
